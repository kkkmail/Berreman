        // property the ablation fact below shows can fail.
        for i in 0 .. 3 do
            Assert.True(norms.[i] > 1.0e-6, $"{parameterNames.[i]} is unobservable in the full measurement set: {report}")

        // Bands pinned per §9 from the observed values, recorded in the implementation log.
        Assert.True(System.Double.IsFinite condition, $"the Jacobian condition number must be finite, got {condition}")
