    [<Fact>]
    member _.``every configuration produces a physically realizable, essentially non-depolarizing Mueller matrix`` () =
        // Two invariants over the whole measurement set.
        //
        // REALIZABILITY is absolute: a negative Cloude eigenvalue would mean the forward model had
        // produced a matrix no real optical element could produce, and no tolerance can excuse that. Only
        // round-off is allowed.
        //
        // NON-DEPOLARIZATION is deliberately NOT asserted strictly, and that is a physics statement rather
        // than a slack tolerance. With numberOfReflections = 3 the plate solver sums the Mueller matrices
        // of the emerging beams INCOHERENTLY, and a sum of Mueller-Jones matrices is in general
        // depolarizing. So the depolarization index is below 1 BY CONSTRUCTION and a test demanding
        // exactly 1 would be asserting something false about the model it is testing.
        //
        // How much depolarization, measured rather than estimated (worst 1 - DI per group):
        //
        //     C1  (z-cut, normal, transmission)   1.1e-16   effectively none
        //     C3  (x-cut, normal, transmission)   2.7e-03
        //     C4  (x-cut, oblique, transmission)  4.2e-03
        //     C2  (z-cut, oblique, transmission)  2.9e-02
        //     C2  (z-cut, oblique, REFLECTION)    9.4e-02
        //     C4  (x-cut, oblique, REFLECTION)    4.2e-01   <- the extreme
        //
        // The pattern is physical and worth understanding, because it is easy to mistake for a defect.
        // TRANSMISSION is dominated by the direct beam: the twice-bounced beam carries only ~0.2 % of it
        // at quartz's 4.55 % surface reflectance, so the sum stays close to a single Mueller-Jones matrix.
        // REFLECTION has no such dominant term - the front-surface reflection (~4.5 %) and the beam that
        // has traversed the plate and reflected internally (~4.1 %) are COMPARABLE in amplitude while
        // undergoing quite different polarization transformations, so summing them genuinely destroys
        // polarization. Hence two bands: a tight one for transmission, where a defect would show, and a
        // loose one for reflection, where 40 % depolarization is the correct answer.
        //
        // A consequence recorded here because it constrains use of this suite: the closed-form analytic
        // inversion assumes a Mueller-Jones matrix, so it is meaningful for the transmission
        // configurations and NOT for the reflection ones. The nonlinear fit is unaffected - it compares
        // against the full Berreman model, which reproduces the depolarization exactly.
        let observations = observe fullConfigurations
        Assert.True(observations.Length > 20, $"the measurement set should be substantial, got {observations.Length}")

        let mutable worstTransmitted = 0.0
        let mutable worstOverall = 0.0
        for o in observations do
            let eigenvalues = cloudeEigenvalues o.measured
            let smallest = List.min eigenvalues
            Assert.True(
                smallest > -1.0e-9,
                $"%A{o.configuration.cut} at {o.configuration.incidenceAngle.value / degree} deg: negative Cloude eigenvalue {smallest} — the matrix is not physically realizable")

            match depolarizationIndex o.measured with
            | Ok di ->
                Assert.True(di <= 1.0 + 1.0e-9, $"depolarization index {di} exceeds 1, which is impossible")
                worstOverall <- max worstOverall (1.0 - di)
                if o.configuration.observable = TransmittedMueller then
                    worstTransmitted <- max worstTransmitted (1.0 - di)
            | Error e -> Assert.Fail($"expected a depolarization index, got %A{e}")

        // Pinned per the spec §9 protocol at ~1.7x and ~1.2x the observed worst values.
        Assert.True(
            worstTransmitted < 0.05,
            $"worst transmission depolarization = {worstTransmitted}; the modelled multiple reflections should contribute a few percent at most")
        Assert.True(
            worstOverall < 0.5,
            $"worst depolarization over the whole set = {worstOverall}; reflection from a thick plate depolarizes strongly, but not without limit")

