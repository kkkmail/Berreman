    [<Fact>]
    member _.``the full measurement set is well conditioned and every parameter is observable`` () =
        // Identifiability, asserted through the two quantities that survive noiseless data.
        //
        // This matters because the obvious diagnostics DO NOT survive. FitQuality computes
        // Cov = reducedChiSquared * (J^T J)^-1, and on noiseless synthetic data the reduced chi-squared is
        // ~1e-30, so the standard errors and confidence intervals it reports collapse toward zero and say
        // nothing about identifiability. Asserting that the truth lies inside a 95 % interval of width
        // ~1e-15 would be a test that passes for the wrong reason.
        //
        // What DOES survive is anything depending on J alone: the column norms (how much the residual
        // moves when one parameter moves) and the condition number (the ratio of the most- to the
        // least-constrained direction in parameter space). The correlation matrix survives too, because
        // the reduced-chi-squared factor cancels in corr = cov / (sigma_i sigma_j).
        //
        // No fit is run here. Identifiability is a property of the Jacobian at the solution, and for
        // noiseless synthetic data the solution IS the ground truth - so the Jacobian is evaluated there
        // directly. That makes this fact a statement about the EXPERIMENT DESIGN rather than about whether
        // a particular optimizer run converged, and it keeps it cheap.
        //
        // A trap worth recording: FitQuality.residualJacobian steps each parameter by
        // sqrt(eps) * max(|x_p|, 1e-12), which is RELATIVE and therefore collapses to ~1e-20 at exactly
        // x = 0. The Jacobian must not be evaluated at the origin of the scaled space; centring the
        // scaling on the perturbed start puts the truth at a non-zero scaled point.
        let observations = observe fullConfigurations
        let scaling = scalingAround perturbedStart
        let residual = residualFor observations scaling
        let truthPoint = toScaled scaling quartz
        Assert.True(truthPoint |> Array.forall (fun x -> abs x > 1.0e-6), "the Jacobian must not be evaluated at the origin of the scaled space")

        let jacobian = FitQuality.residualJacobian residual truthPoint
        let norms = jacobianColumnNorms jacobian
        let condition = jacobianCondition jacobian
        let report = System.String.Join("; ", [ for i in 0 .. 3 -> $"{parameterNames.[i]} |J| = {norms.[i]}" ])

        // Every parameter must actually move the residual - this is what "observable" means, and it is the
        // property the ablation fact below shows can fail.
        for i in 0 .. 3 do
            Assert.True(norms.[i] > 1.0e-6, $"{parameterNames.[i]} is unobservable in the full measurement set: {report}")

        // Bands pinned per §9 from the observed values, recorded in the implementation log.
        Assert.True(System.Double.IsFinite condition, $"the Jacobian condition number must be finite, got {condition}")
        Assert.True(condition < 5.0e3, $"Jacobian condition number = {condition}; {report}")

        // The correlation matrix is scale-free and therefore meaningful even at zero residual.
        //
        // MEASURED RESULT, and a genuine property of this experiment design rather than a slack tolerance:
        // n_o and n_e are correlated at 0.99999. That is physical. Linear retardance depends on the
        // DIFFERENCE n_e - n_o through 2 pi (n_e - n_o) d / lambda, and that difference is 0.009 against
        // absolute indices of 1.54 - so the data constrains the difference about 170 times better than it
        // constrains the common level, and moving both indices together is very nearly a null direction.
        // The fit still resolves both (the round-trip fact recovers each to better than 1e-3 relative),
        // because "very nearly" is not "exactly": the Fresnel amplitudes and the internal refraction angle
        // do depend on the absolute level, which is precisely what the oblique-incidence and reflection
        // configurations contribute.
        //
        // The band is therefore pinned just above the observed 0.99999 for the index pair, and much
        // tighter for every other pair, so that a genuine degeneracy - an experiment set that lost the
        // absolute-index information altogether - would still fail this fact.
        // The correlation is computed from the JACOBIAN, not from FitQuality.reportFrom. FitQuality
        // derives it from Cov = reducedChiSquared * (J^T J)^-1, and although the reducedChiSquared factor
        // cancels in the ratio ALGEBRAICALLY, it does not cancel in floating point: here the reduced
        // chi-squared is ~1e-30, the covariance diagonal underflows, and the report's zero-guard returns a
        // flat 0.0 for every off-diagonal - a value indistinguishable from "perfectly independent" and so
        // actively misleading. This was measured, not assumed. FitQuality is still the right tool once
        // real noise is present; jacobianCorrelation is the diagnostic for the noiseless case.
        let correlation = jacobianCorrelation jacobian
        let pairs =
            [ for i in 0 .. 3 do
                for j in i + 1 .. 3 ->
                    $"{parameterNames.[i]}/{parameterNames.[j]}", abs correlation.[i].[j] ]
        let pairReport = System.String.Join("; ", [ for (n, c) in pairs -> $"{n} = {c}" ])
        for (name, corr) in pairs do
            let bound = if name = "n_o/n_e" then 0.999999 else 0.5
            Assert.True(corr < bound, $"parameter correlation {name} = {corr} exceeds {bound}; all pairs: {pairReport}")

    [<Fact>]
    member _.``C1 alone cannot determine three of the four constants, which is why the design needs more cuts`` () =
        // The ablation, and the executable answer to "what experiments are needed". Asserting the FAILURE
        // is what turns the multi-configuration design from an assumption into a result.
        //
        // Propagating along the optic axis at normal incidence, the wave sees only the transverse Rho
        // components (both g11) and the ordinary index; the crystal 3-axis is parallel to the propagation
        // direction, so neither n_e nor g33 has ANY effect at all - their Jacobian columns are identically
        // zero, not merely small.
        //
        // n_o is the interesting case, and the measured answer is subtler than "it divides out". The
        // normalized matrix does still depend on it, but only through a second-order channel: the plate
        // emits a direct beam rotated by psi and a twice-bounced beam rotated by 3 psi, and n_o sets the
        // RELATIVE WEIGHT of the two through the surface reflectance. Because 2x2 rotations commute and
        // form a one-parameter group, that weighted sum is itself exactly a scaled rotation - which is why
        // C1 shows no depolarization at all (measured index of departure 1.1e-16) even though two beams
        // are being summed - but its ANGLE shifts slightly with the weight, and hence with n_o. The
        // measured sensitivity is real, not numerical noise: it is about three orders of magnitude below
        // g11's and about three orders above the forward model's numerical floor.
        //
        // So C1 leaves two parameters structurally invisible and a third constrained ~700 times more
        // weakly than the one it actually measures. That is what "one configuration is not enough" means
        // quantitatively.
        // The Jacobian is evaluated at the TRUTH, expressed in a scaling centred on the perturbed start so
        // that no coordinate is exactly zero. That detail is load-bearing: FitQuality.residualJacobian
        // steps each parameter by sqrt(eps) * max(|x_p|, 1e-12), which collapses to ~1e-20 at x = 0 and
        // would report EVERY column as dead — including the one that is genuinely alive, turning this fact
        // into a false positive.
        let scaling = scalingAround perturbedStart
        let truthPoint = toScaled scaling quartz
        let residual = residualFor (observe c1) scaling
        let jacobian = FitQuality.residualJacobian residual truthPoint
        let norms = jacobianColumnNorms jacobian
        let report = System.String.Join("; ", [ for i in 0 .. 3 -> $"{parameterNames.[i]} |J| = {norms.[i]}" ])

        // g11 is what C1 measures, and it must be strongly constrained.
        Assert.True(norms.[2] > 1.0e-3, $"g11 must be observable from C1: {report}")

        // n_e and g33 are STRUCTURALLY invisible - exactly zero, not merely small.
        for i in [ 1; 3 ] do
            Assert.True(norms.[i] = 0.0, $"{parameterNames.[i]} must be exactly UNOBSERVABLE from C1 alone: {report}")

        // n_o survives only through the multiple-reflection channel described above, at roughly a
        // thousandth of g11's sensitivity. Both halves of that are asserted: it is not zero (so the
        // channel is real), and it is negligible against g11 (so C1 does not usefully determine it).
        Assert.True(norms.[0] > 0.0, $"n_o should retain a weak multiple-reflection sensitivity: {report}")
        Assert.True(
            norms.[0] < norms.[2] / 100.0,
            $"n_o must be far more weakly constrained than g11 from C1 alone: {report}")

        // With two dead directions the problem is singular, not merely ill conditioned.
        let condition = jacobianCondition jacobian
        Assert.True(
            condition > 1.0e12,
            $"C1 alone must be singular, got condition number {condition}; {report}")

        // Adding C3 - the second crystal cut - restores the other three, which is precisely the design
        // claim: it is the CUT that buys observability, not more angles on the same sample.
        let restoredResidual = residualFor (observe (c1 @ c3)) scaling
        let restoredNorms = jacobianColumnNorms (FitQuality.residualJacobian restoredResidual truthPoint)
        let restoredReport = System.String.Join("; ", [ for i in 0 .. 3 -> $"{parameterNames.[i]} |J| = {restoredNorms.[i]}" ])
        for i in 0 .. 3 do
            Assert.True(restoredNorms.[i] > 1.0e-6, $"adding the second cut must make {parameterNames.[i]} observable: {restoredReport}")
