        // is what turns the multi-configuration design from an assumption into a result.
        //
        // Propagating along the optic axis at normal incidence, the wave sees only the transverse Rho
        // components (both g11) and the ordinary index; the crystal 3-axis is parallel to the propagation
        // direction, so neither n_e nor g33 has ANY effect at all - their Jacobian columns are identically
        // zero, not merely small.
        //
        // n_o is the interesting case, and the measured answer is subtler than "it divides out". The
        // normalized matrix does still depend on it, but only through a second-order channel: the plate
        // emits a direct beam rotated by psi and a twice-bounced beam rotated by 3 psi, and n_o sets the
        // RELATIVE WEIGHT of the two through the surface reflectance. Because 2x2 rotations commute and
        // form a one-parameter group, that weighted sum is itself exactly a scaled rotation - which is why
        // C1 shows no depolarization at all (measured index of departure 1.1e-16) even though two beams
        // are being summed - but its ANGLE shifts slightly with the weight, and hence with n_o. The
        // measured sensitivity is real, not numerical noise: it is about three orders of magnitude below
        // g11's and about three orders above the forward model's numerical floor.
        //
        // So C1 leaves two parameters structurally invisible and a third constrained ~700 times more
        // weakly than the one it actually measures. That is what "one configuration is not enough" means
        // quantitatively.
        // The Jacobian is evaluated at the TRUTH, expressed in a scaling centred on the perturbed start so
        // that no coordinate is exactly zero. That detail is load-bearing: FitQuality.residualJacobian
        // steps each parameter by sqrt(eps) * max(|x_p|, 1e-12), which collapses to ~1e-20 at x = 0 and
        // would report EVERY column as dead — including the one that is genuinely alive, turning this fact
        // into a false positive.
        let scaling = scalingAround perturbedStart
        let truthPoint = toScaled scaling quartz
        let residual = residualFor forward (observe c1) scaling
        let jacobian = FitQuality.residualJacobian residual truthPoint
        let norms = jacobianColumnNorms jacobian
        let report = System.String.Join("; ", [ for i in 0 .. 3 -> $"{parameterNames.[i]} |J| = {norms.[i]}" ])

        // g11 is what C1 measures, and it must be strongly constrained.
        Assert.True(norms.[2] > 1.0e-3, $"g11 must be observable from C1: {report}")

        // n_e and g33 are STRUCTURALLY invisible - exactly zero, not merely small.
        for i in [ 1; 3 ] do
            Assert.True(norms.[i] = 0.0, $"{parameterNames.[i]} must be exactly UNOBSERVABLE from C1 alone: {report}")

        // n_o survives only through the multiple-reflection channel described above, at roughly a
        // thousandth of g11's sensitivity. Both halves of that are asserted: it is not zero (so the
        // channel is real), and it is negligible against g11 (so C1 does not usefully determine it).
        Assert.True(norms.[0] > 0.0, $"n_o should retain a weak multiple-reflection sensitivity: {report}")
        Assert.True(
            norms.[0] < norms.[2] / 100.0,
            $"n_o must be far more weakly constrained than g11 from C1 alone: {report}")

        // With two dead directions the problem is singular, not merely ill conditioned.
        let condition = jacobianCondition jacobian
        Assert.True(
            condition > 1.0e12,
            $"C1 alone must be singular, got condition number {condition}; {report}")

