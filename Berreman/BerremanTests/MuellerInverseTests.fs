    [<Fact>]
    member _.``C1 is a pure optical rotator whose rotatory power is exactly 2 pi g11 d over lambda`` () =
        // The most valuable fact in this file: an end-to-end check of the whole forward chain - material
        // assembly, the Rho.fromIm sign convention, Berreman propagation, plate multiple reflections and
        // muellerMatrixT() - against a CLOSED FORM, at machine precision.
        //
        // What the engine actually does, established by measuring it (varying g11, g33, n and d
        // independently) rather than assumed:
        //
        //     Delta_n_circular = 2 * rho_transverse      ->   specific rotation = 2 pi g11 / lambda
        //
        // It is driven by the TRANSVERSE Rho component g11, is exactly independent of g33, and is exactly
        // independent of the refractive index. Agreement with the closed form is to 2e-16 relative.
        //
        // A CONVENTION WARNING, and the reason this fact does not assert the literature figure. The
        // engine's Rho is the bi-anisotropic (Tellegen-Post) magnetoelectric tensor of D = eps E + rho H,
        // not the crystallographic gyration tensor g of D = eps E + i (G x E). The two share the symbol g
        // in the literature and in Active.Rho.type_3_4_6_Crystal, but they are different
        // parameterizations. Reading the same quartz constants crystallographically gives
        // pi g33 / (n lambda) = 18.62 deg/mm, which matches the MEASURED rotatory power of alpha-quartz at
        // 632.8 nm (18.8 deg/mm) to within 1 %; reading them as this engine does gives 33.57 deg/mm. To
        // make the engine reproduce 18.8 deg/mm the transverse Rho component would have to be 3.305e-5,
        // not 5.9e-5. Neither number is wrong - they answer different questions - but anyone quoting a
        // gyration value out of this pipeline must know which one they have.
        //
        // If this fact fails, the forward model has changed and every inverse result below is meaningless,
        // which is exactly why it is asserted before anything is fitted.
        let observations = observe c1
        let m = (List.exactlyOne observations).measured

        match analyticInversion m with
        | Ok a ->
            // A pure rotator has no linear birefringence in either basis: along the optic axis the two
            // transverse directions are equivalent, so there is nothing to retard against anything else.
            Assert.True(abs a.lb.degrees < 1.0e-6, $"C1 linear retardance at 0 deg = {a.lb.degrees} deg, expected ~0")
            Assert.True(abs a.lbPrime.degrees < 1.0e-6, $"C1 linear retardance at 45 deg = {a.lbPrime.degrees} deg, expected ~0")

            // The circular retardance is twice the azimuth rotation, so the rotation over the plate is
            // |cb| / 2 degrees.
            // Both lengths carry the engine's `meter` unit, so their ratio is dimensionless by
            // construction — the unit system is doing the bookkeeping rather than a comment.
            let plateMeters =
                match thickPlate with
                | Thickness t -> t
                | Infinity -> failwith "the C1 plate must have a finite thickness"
            let platesPerWave = plateMeters / waveLength.value
            let predictedDeg = 2.0 * System.Math.PI * abs quartzG11.value * platesPerWave / degree
            let rotationDeg = abs a.cb.degrees / 2.0
            let relative = abs (rotationDeg - predictedDeg) / predictedDeg
            // Pinned per the spec §9 protocol from an observed relative deviation of 2.1e-16 — i.e. the
            // engine reproduces the closed form to the last bit a double can carry.
            Assert.True(
                relative < 1.0e-12,
                $"C1 rotation = {rotationDeg} deg; closed form 2*pi*g11*d/lambda = {predictedDeg} deg (relative deviation {relative})")

            // And it is transparent: no dichroism of any kind.
            Assert.True(transparencyResidual a < 1.0e-9, $"C1 transparency residual = {transparencyResidual a}")
        | Error e -> Assert.Fail($"C1 should invert to a pure rotator, got %A{e}")

